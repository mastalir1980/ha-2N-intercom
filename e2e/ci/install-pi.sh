#!/usr/bin/env bash
# One-time (and after every change to e2e/ci/ha2n-staging) install of the Pi CI runner plumbing.
# Run ON THE PI from your own clone, as yourself with sudo:
#
#   sudo bash e2e/ci/install-pi.sh            # staging user = the user who ran sudo
#   sudo bash e2e/ci/install-pi.sh <user>     # explicit staging user (owner of ~/ha-staging, in docker group)
#
# Creates/updates: user ha2n-ci (NO docker), /usr/local/sbin/ha2n-staging, /etc/ha2n-ci/staging.conf,
# /etc/ha2n-ci/e2e.env (template, only if missing), /etc/sudoers.d/ha2n-ci, venv + reports under
# /var/lib/ha2n-ci. Idempotent. Does not register the GitHub runner — see e2e/ci/README.md.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STAGING_USER="${1:-${SUDO_USER:-}}"
[ -n "$STAGING_USER" ] && [ "$STAGING_USER" != root ] || { echo "pass the staging user: sudo bash $0 <user>" >&2; exit 1; }
STAGING_HOME="$(getent passwd "$STAGING_USER" | cut -d: -f6)"
STAGING_DIR="$STAGING_HOME/ha-staging"
CI_USER=ha2n-ci; CI_HOME=/var/lib/ha2n-ci
[ -f "$STAGING_DIR/docker-compose.yml" ] || { echo "no $STAGING_DIR/docker-compose.yml — bootstrap staging first" >&2; exit 1; }
id -nG "$STAGING_USER" | grep -qw docker || { echo "$STAGING_USER is not in the docker group" >&2; exit 1; }

echo "==> user $CI_USER (no docker access)"
id "$CI_USER" >/dev/null 2>&1 || useradd --system --create-home --home-dir "$CI_HOME" --shell /bin/bash "$CI_USER"
if id -nG "$CI_USER" | grep -qw docker; then gpasswd -d "$CI_USER" docker; fi
install -d -o "$CI_USER" -g "$CI_USER" -m 0750 "$CI_HOME" "$CI_HOME/reports"

echo "==> /usr/local/sbin/ha2n-staging (root-owned)"
install -o root -g root -m 0755 "$SRC/ha2n-staging" /usr/local/sbin/ha2n-staging

echo "==> /usr/local/lib/ha2n-ci/job-started.sh (runner gate, root-owned)"
install -d -o root -g root -m 0755 /usr/local/lib/ha2n-ci
install -o root -g root -m 0755 "$SRC/job-started-hook.sh" /usr/local/lib/ha2n-ci/job-started.sh

echo "==> /etc/ha2n-ci"
install -d -o root -g root -m 0755 /etc/ha2n-ci
cat > /etc/ha2n-ci/staging.conf <<CONF
# Generated by e2e/ci/install-pi.sh — root-owned, read by ha2n-staging and pr-e2e.sh. No secrets here.
STAGING_USER=$STAGING_USER
STAGING_DIR=$STAGING_DIR
HA_CONTAINER=ha-staging
HA_URL=http://127.0.0.1:8124
REPO_URL=https://github.com/mastalir1980/ha-2N-intercom.git
MIRROR=$STAGING_HOME/.ha2n-ci/mirror.git
CI_HOME=$CI_HOME
E2E_ENV=/etc/ha2n-ci/e2e.env
CONF
chmod 0644 /etc/ha2n-ci/staging.conf
# The helper uses THIS root-owned compose file, never ~/ha-staging/docker-compose.yml (writable,
# and overwritten by deploy.sh). Refuse anything that could reach the host.
if grep -Eiq 'privileged|docker\.sock|network_mode|pid:|cap_add|devices:|/:/' "$SRC/../staging/docker-compose.yml"; then
  echo "e2e/staging/docker-compose.yml contains host-level options — refusing" >&2; exit 1
fi
install -o root -g root -m 0644 "$SRC/../staging/docker-compose.yml" /etc/ha2n-ci/staging-compose.yml
install -d -o "$STAGING_USER" -g "$STAGING_USER" -m 0700 "$STAGING_HOME/.ha2n-ci"
if [ ! -f /etc/ha2n-ci/allowed-actors ]; then
  printf '%s\n' mastalir1980 > /etc/ha2n-ci/allowed-actors
fi
chown root:root /etc/ha2n-ci/allowed-actors; chmod 0644 /etc/ha2n-ci/allowed-actors
if [ ! -f /etc/ha2n-ci/e2e.env ]; then
  { echo "# E2E settings for the Pi CI runner. Readable by $CI_USER only (and root)."
    echo "# Use the READ-ONLY 2N account here (Monitoring, no Control) — see e2e/ci/README.md."
    grep -v -e '^PI_SSH=' -e '^PI_STAGING_DIR=' -e '^HA_CONTAINER=' -e '^E2E_GRANT_USER_UUID=' "$SRC/../.env.example" \
      | sed -e 's#^HA_URL=.*#HA_URL=http://127.0.0.1:8124#' -e 's#^E2E_RELAY_NUMBERS=.*#E2E_RELAY_NUMBERS=#' \
            -e 's#^E2E_AGENT=.*#E2E_AGENT=0#'
  } > /etc/ha2n-ci/e2e.env
  echo "    -> fill in /etc/ha2n-ci/e2e.env (sudo nano /etc/ha2n-ci/e2e.env)"
fi
chown root:"$CI_USER" /etc/ha2n-ci/e2e.env; chmod 0640 /etc/ha2n-ci/e2e.env

echo "==> sudoers: $CI_USER may run only ha2n-staging, only as $STAGING_USER"
TMP="$(mktemp)"
echo "$CI_USER ALL=($STAGING_USER) NOPASSWD: /usr/local/sbin/ha2n-staging" > "$TMP"
visudo -cf "$TMP" >/dev/null
install -o root -g root -m 0440 "$TMP" /etc/sudoers.d/ha2n-ci; rm -f "$TMP"

echo "==> python venv for the tests"
python3 -c 'import ensurepip' 2>/dev/null || apt-get install -y python3-venv
[ -d "$CI_HOME/venv" ] || sudo -u "$CI_USER" -H python3 -m venv "$CI_HOME/venv"
sudo -u "$CI_USER" -H "$CI_HOME/venv/bin/pip" install -q --upgrade pip
# via stdin: $SRC is in the staging user's home, which ha2n-ci cannot read (0700 on Bookworm)
sudo -u "$CI_USER" -H "$CI_HOME/venv/bin/pip" install -q -r /dev/stdin < "$SRC/../requirements.txt"

RUNNER_DIR="$CI_HOME/actions-runner"
if [ -f "$RUNNER_DIR/.runner" ]; then
  echo "==> runner found: enabling the job-started gate"
  HOOK_LINE=ACTIONS_RUNNER_HOOK_JOB_STARTED=/usr/local/lib/ha2n-ci/job-started.sh
  touch "$RUNNER_DIR/.env"
  grep -qxF "$HOOK_LINE" "$RUNNER_DIR/.env" || echo "$HOOK_LINE" >> "$RUNNER_DIR/.env"
  # root-owned so a job cannot switch the gate off for the next job
  chown root:"$CI_USER" "$RUNNER_DIR/.env"; chmod 0644 "$RUNNER_DIR/.env"
  for svc in /etc/systemd/system/actions.runner.*.service; do
    [ -e "$svc" ] && systemctl restart "$(basename "$svc")" && echo "    restarted $(basename "$svc")"
  done
else
  echo "==> no runner registered yet — after registering, run this script again to enable the gate"
fi

echo "==> self-check"
sudo -u "$CI_USER" sudo -n -u "$STAGING_USER" /usr/local/sbin/ha2n-staging status
if sudo -u "$CI_USER" docker ps >/dev/null 2>&1; then echo "!! $CI_USER can use docker — fix this" >&2; exit 1; fi
echo "OK. Next: fill /etc/ha2n-ci/e2e.env, then register the runner (e2e/ci/README.md, step 4)."
